use std::fs;
use std::path::PathBuf;
use std::process::Command;

use anyhow::{Context, Result};

use crate::apply::ThemePaths;
use crate::scheme::{MaterialYouScheme, PywalScheme};

/// Paths of written Pywal cache files in `<cache_dir>/wal/`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PywalArtifacts {
    pub colors_json_path: PathBuf,
    pub colors_plain_path: PathBuf,
    pub colors_sh_path: PathBuf,
    pub colors_css_path: PathBuf,
}

fn color_n<'a>(scheme: &'a PywalScheme, idx: usize) -> &'a str {
    let key = format!("color{idx}");
    scheme
        .colors
        .get(&key)
        .map(String::as_str)
        .unwrap_or("#000000")
}

/// Generate the plain-text `~/.cache/wal/colors` file (16 hex colors, one per line).
pub fn generate_pywal_colors_plain(pywal_scheme: &PywalScheme) -> String {
    let mut out = String::new();
    for i in 0..16 {
        out.push_str(color_n(pywal_scheme, i));
        out.push('\n');
    }
    out
}

/// Generate the shell variables file `~/.cache/wal/colors.sh`.
pub fn generate_pywal_colors_sh(pywal_scheme: &PywalScheme) -> String {
    let mut out = String::new();
    out.push_str("# Shell variables\n# Generated by 'kde-material-you-colors'\n");
    out.push_str(&format!("wallpaper=\"{}\"\n\n", pywal_scheme.wallpaper));
    out.push_str("# Special\n");
    out.push_str(&format!(
        "background='{}'\n",
        pywal_scheme.special.background
    ));
    out.push_str(&format!(
        "foreground='{}'\n",
        pywal_scheme.special.foreground
    ));
    out.push_str(&format!("cursor='{}'\n\n", pywal_scheme.special.cursor));
    out.push_str("# Colors\n");
    for i in 0..16 {
        out.push_str(&format!("color{i}='{}'\n", color_n(pywal_scheme, i)));
    }
    out
}

/// Generate the CSS custom properties file `~/.cache/wal/colors.css`.
pub fn generate_pywal_colors_css(pywal_scheme: &PywalScheme) -> String {
    let mut out = String::new();
    out.push_str("/* CSS variables\n   Generated by 'kde-material-you-colors' */\n:root {\n");
    out.push_str(&format!(
        "    --wallpaper: url(\"{}\");\n\n",
        pywal_scheme.wallpaper
    ));
    out.push_str("    /* Special */\n");
    out.push_str(&format!(
        "    --background: {};\n",
        pywal_scheme.special.background
    ));
    out.push_str(&format!(
        "    --foreground: {};\n",
        pywal_scheme.special.foreground
    ));
    out.push_str(&format!("    --cursor: {};\n\n", pywal_scheme.special.cursor));
    out.push_str("    /* Colors */\n");
    for i in 0..16 {
        out.push_str(&format!("    --color{i}: {};\n", color_n(pywal_scheme, i)));
    }
    out.push_str("}\n");
    out
}

/// Write `~/.cache/wal/colors.json`, `colors`, `colors.sh`, and `colors.css` (plus optional `wal` reload).
pub fn write_pywal_files(
    scheme: &MaterialYouScheme,
    is_pywal_light: bool,
    paths: &ThemePaths,
    run_external_commands: bool,
) -> Result<PywalArtifacts> {
    let wal_dir = paths.wal_cache_dir();
    fs::create_dir_all(&wal_dir).with_context(|| {
        format!(
            "failed to create pywal cache directory at {}",
            wal_dir.display()
        )
    })?;

    let pywal_scheme = if is_pywal_light {
        &scheme.pywal.light
    } else {
        &scheme.pywal.dark
    };

    let colors_json_path = wal_dir.join("colors.json");
    let colors_plain_path = wal_dir.join("colors");
    let colors_sh_path = wal_dir.join("colors.sh");
    let colors_css_path = wal_dir.join("colors.css");

    let json_str = serde_json::to_string_pretty(pywal_scheme)
        .context("failed to serialize pywal colors.json")?;
    fs::write(&colors_json_path, json_str)?;
    fs::write(&colors_plain_path, generate_pywal_colors_plain(pywal_scheme))?;
    fs::write(&colors_sh_path, generate_pywal_colors_sh(pywal_scheme))?;
    fs::write(&colors_css_path, generate_pywal_colors_css(pywal_scheme))?;

    if run_external_commands {
        let _ = Command::new("wal")
            .arg("-R")
            .arg("-n")
            .arg("-q")
            .output();
    }

    Ok(PywalArtifacts {
        colors_json_path,
        colors_plain_path,
        colors_sh_path,
        colors_css_path,
    })
}

/// Spawn `on_change_hook` asynchronously via `sh -c <hook>` when `run_external_commands` is `true`
/// and `hook` is non-empty, matching `utils.py:run_hook`.
/// Returns `Ok(true)` if the hook was configured (and spawned when `run_external_commands` is `true`).
pub fn spawn_on_change_hook(hook: Option<&str>, run_external_commands: bool) -> Result<bool> {
    let Some(cmd_str) = hook.map(str::trim).filter(|s| !s.is_empty()) else {
        return Ok(false);
    };

    if run_external_commands {
        Command::new("sh")
            .arg("-c")
            .arg(cmd_str)
            .spawn()
            .with_context(|| format!("failed to spawn on_change_hook '{cmd_str}'"))?;
    }

    Ok(true)
}
